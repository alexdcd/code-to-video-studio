def safe_target_path(value, label):
    if not isinstance(value, str) or not value or Path(value).is_absolute() or "\\" in value:
        raise SystemExit(f"invalid target {label}: {value!r}")
    parts = Path(value).parts
    if any(part in {"", ".", ".."} for part in parts):
        raise SystemExit(f"unsafe target {label}: {value!r}")
    return Path(*parts)


def target_command(value, label):
    import shlex
    if value is None:
        return None
    command = shlex.split(value) if isinstance(value, str) else value
    if not isinstance(command, list) or not command or any(not isinstance(part, str) or not part for part in command):
        raise SystemExit(f"invalid target {label}; use a command string or argv array")
    return command


def load_target(target_id, project_root, config_path=None):
    skill_root = Path(__file__).resolve().parents[1]
    if config_path:
        candidate = Path(config_path).expanduser()
        if not candidate.is_absolute(): candidate = project_root / candidate
    else:
        private_target = project_root / "tools" / "skill-targets" / f"{target_id}.json"
        bundled_target = skill_root / "adapters" / target_id / "target.json"
        candidate = private_target if private_target.is_file() else bundled_target
    if not candidate.is_file():
        raise SystemExit(f"target config not found for {target_id}: {candidate}")
    target = read_json(candidate)
    if target.get("schemaVersion") != 1 or target.get("id") != target_id:
        raise SystemExit(f"invalid target config identity in {candidate}")
    target["characterDir"] = safe_target_path(target.get("characterDir"), "characterDir").as_posix()
    target["assetPrefix"] = safe_target_path(target.get("assetPrefix"), "assetPrefix").as_posix()
    runtime = target.get("runtime")
    if not isinstance(runtime, str) or not re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", runtime):
        raise SystemExit(f"invalid target runtime global: {runtime!r}")
    target["runtime"] = runtime
    for key in ("versionFile",):
        if target.get(key): target[key] = safe_target_path(target[key], key).as_posix()
    for key in ("buildCommand", "catalogCommand"):
        if target.get(key): target[key] = target_command(target[key], key)
    if target.get("versionBump", "minor") != "minor":
        raise SystemExit("only the 'minor' target version bump policy is supported")
    return target


def finalize_target(project_root: Path, target: dict):
    version_path = project_root / target["versionFile"] if target.get("versionFile") else None
    old_content = version_path.read_text(encoding="utf-8") if version_path else None
    old_version = old_content.strip() if old_content is not None else None
    new_version = None
    if version_path:
        match = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", old_version or "")
        if not match: raise SystemExit(f"unsupported target version: {old_version}")
        new_version = f"{match.group(1)}.{int(match.group(2)) + 1}.0"
        version_path.write_text(new_version + "\n", encoding="utf-8")
    commands = [cmd for cmd in (target.get("buildCommand"), target.get("catalogCommand")) if cmd]
    try:
        for command in commands:
            subprocess.run(command, cwd=project_root, check=True)
    except Exception:
        if version_path and old_content is not None:
            version_path.write_text(old_content, encoding="utf-8")
        raise
    return {"oldVersion": old_version, "newVersion": new_version, "commands": commands}


