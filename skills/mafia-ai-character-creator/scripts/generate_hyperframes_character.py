#!/usr/bin/env python3
"""Export a character package into a configured HyperFrames kit target.

Supported authoring routes:
- generated-art / raster-sprites: sprite atlas -> target runtime namespace
- raster-puppet: articulated image parts -> target runtime namespace

The exported runtime is non-ESM so the target kit builder can embed it. It uses
the configured runtime's `porCuadro` helper for seek-safe playback and optional
`anim` helpers for wrapper acting.

By default this command only writes the target's configured character directory.
With --finalize, it applies the target's version policy and runs configured
build/catalog commands. Finalization is opt-in because those are repository mutations.
"""
