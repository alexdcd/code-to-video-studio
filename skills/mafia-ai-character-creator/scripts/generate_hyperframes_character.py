def namespace_for(slug: str) -> str:
    parts = [p for p in re.split(r'[^A-Za-z0-9]+', slug) if p]
    return (parts[0].lower() + ''.join(x[:1].upper() + x[1:] for x in parts[1:])) if parts else 'character'


def js_json(value) -> str:
    # Keep the generated kit JS safe for HTML script embedding.
    return json.dumps(value, ensure_ascii=False, separators=(',', ':')).replace('<', r'\u003c')


